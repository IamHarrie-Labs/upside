import { readFileSync, writeFileSync } from "node:fs";
const root = new URL("../", import.meta.url);
const tokens = JSON.parse(readFileSync(new URL("brand/tokens.json", root), "utf8"));
writeFileSync(new URL("app/src/brand.css", root), `/* Generated by scripts/sync-brand.mjs. */\n:root {\n${Object.entries(tokens).map(([k,v]) => `  --${k === "panel2" ? "panel-2" : k}: ${v};`).join("\n")}\n}\n`);
writeFileSync(new URL("mobile/src/theme.ts", root), `// Generated by scripts/sync-brand.mjs.\nexport const C = ${JSON.stringify(tokens, null, 2)} as const;\n`);
console.log("Synced web and native brand tokens.");
