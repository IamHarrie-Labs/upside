// Copies contract ABIs from Foundry's build output into the app and keeper as typed constants.
// Run after `forge build`:  node scripts/export-abi.mjs
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const names = [
  "CallBook",
  "FollowVault",
  "VaultFactory",
  "AttestedGate",
  "KeeperPriceSource",
  "UpsideConfig",
  "DemoRouter",
  "DemoToken",
];

let out = "// Generated by scripts/export-abi.mjs. Do not edit.\n";
for (const name of names) {
  const artifact = JSON.parse(readFileSync(join(root, "contracts/out", `${name}.sol`, `${name}.json`), "utf8"));
  out += `export const ${name}Abi = ${JSON.stringify(artifact.abi)} as const;\n`;
}
for (const target of ["app/src/abi.ts", "keeper/src/abi.ts"]) {
  writeFileSync(join(root, target), out);
  console.log("wrote", target);
}
